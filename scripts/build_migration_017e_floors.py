#!/usr/bin/env python3
"""
Turn scripts/floors_crosscheck.csv (from check_floors.py) into
migrations/017e_floor_crosscheck.sql.

A floor count is shown as fact only when it holds up against a second source.
Sources, most specific first: Wikipedia infobox, Wikidata, NYC MapPLUTO,
OpenStreetMap building:levels.

  agree      two or more sources within 1 floor -> that value, fact
             (taken from the most specific agreeing source)
  conflict   sources disagree and no two agree -> the Wikipedia/Wikidata
             value if there is one, else the highest value, estimate. Both failure modes seen in the data undercount:
             OSM tags a tower's podium, PLUTO sometimes describes a
             low-rise lot. The UI marks it "· est".
  filled     no OSM count, PLUTO/Wikipedia has one -> that value, estimate
             (one source, so not a fact yet)
  single     only the existing OSM value -> unchanged

Writes scripts/floors_decisions.csv alongside the SQL so every change is
traceable to its sources.
"""
import csv, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IN = os.path.join(ROOT, "scripts", "floors_crosscheck.csv")
OUT = os.path.join(ROOT, "migrations", "017e_floor_crosscheck.sql")
DEC = os.path.join(ROOT, "scripts", "floors_decisions.csv")
ORDER = ["wikipedia", "wikidata", "pluto", "osm"]


def num(v):
    return int(float(v)) if v not in ("", None, "None") else None


def decide(r):
    vals = {k: num(r[k]) for k in ORDER if k in r}
    have = {k: v for k, v in vals.items() if v is not None}
    osm, osm_ver = vals["osm"], r["osm_verified"] == "True"
    if not have:
        return None
    if len(have) == 1 and "osm" in have:
        return None  # nothing to compare against
    if osm is None:
        k = next(k for k in ORDER if k in have)
        return ("filled", have[k], False, k)
    # find the most specific source that some other source agrees with
    for k in ORDER:
        if k in have and any(abs(have[k] - have[j]) <= 1 for j in have if j != k):
            agreeing = [j for j in have if abs(have[k] - have[j]) <= 1]
            # A one-floor gap between OSM and PLUTO is counting style, not an
            # error: keep the number already shown unless an encyclopedia
            # entry for the building gives its own.
            if "osm" in agreeing and k not in ("wikipedia", "wikidata"):
                return ("agree", have["osm"], True, "+".join(agreeing))
            return ("agree", have[k], True, "+".join(agreeing))
    # No two agree. A name-matched encyclopedia entry for that exact building
    # beats a guess; otherwise take the highest, since both failure modes
    # undercount (an OSM podium part, a low-rise PLUTO lot).
    for k in ("wikipedia", "wikidata"):
        if k in have:
            return ("conflict", have[k], False, k)
    top = max(have, key=lambda k: have[k])
    return ("conflict", have[top], False, top)


def main():
    rows = list(csv.DictReader(open(IN)))
    sql, dec, counts = [], [], {}
    for r in rows:
        d = decide(r)
        if not d:
            continue
        kind, value, fact, why = d
        counts[kind] = counts.get(kind, 0) + 1
        osm, osm_ver = num(r["osm"]), r["osm_verified"] == "True"
        dec.append({"id": r["id"], "name": r["name"], "decision": kind, "stories": value, "fact": fact,
                    "basis": why, "osm": r["osm"], "pluto": r["pluto"], "wikidata": r["wikidata"],
                    "wikipedia": r.get("wikipedia", ""), "wikipedia_title": r.get("wikipedia_title", ""),
                    "pluto_lot": r["pluto_lot"]})
        if value != osm or fact != osm_ver:
            label = r["name"].replace("*/", "")
            sql.append(f"update buildings set stories = {value}, stories_verified = {str(fact).lower()} "
                       f"where id = {r['id']};  -- {label}: {kind} ({why}); was {osm if osm is not None else 'NULL'}"
                       f"{'' if osm_ver else ' est'}")
    with open(DEC, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(dec[0].keys()))
        w.writeheader(); w.writerows(dec)
    head = [
        "-- ============================================================",
        "-- 017e: floor counts checked against a second source",
        "-- (generated by scripts/build_migration_017e_floors.py from",
        "-- scripts/floors_crosscheck.csv; decisions in floors_decisions.csv)",
        "-- Sources: Wikipedia infobox, Wikidata, NYC MapPLUTO, OpenStreetMap.",
        f"-- {', '.join(f'{k}: {v}' for k, v in sorted(counts.items()))}",
        f"-- {len(sql)} rows change. Run in the Supabase SQL Editor. Safe to re-run.",
        "-- ============================================================",
        "begin;", "",
    ]
    tail = ["", "commit;", "",
            "select count(*) filter (where stories is not null) as with_floors,",
            "       count(*) filter (where stories_verified) as floors_as_fact,",
            "       count(*) filter (where stories is not null and not stories_verified) as floors_estimated",
            "from buildings;", ""]
    open(OUT, "w").write("\n".join(head + sql + tail))
    print(f"wrote {OUT}: {len(sql)} changes; {counts}")


if __name__ == "__main__":
    main()
